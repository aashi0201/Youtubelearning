/**
 * Returns a randomized, distinct slice of suggested courses.
 * Ensures variety across categories every time it is called.
 */
export function getRandomSuggestedCourses(count = 4, excludeIds = [], categoryFilter = null) {
  let pool = [...ALL_SUGGESTED_COURSES];

  if (categoryFilter && categoryFilter !== "All") {
    const filterLower = categoryFilter.toLowerCase();
    const matched = pool.filter((c) =>
      c.category.toLowerCase().includes(filterLower) ||
      c.tag.toLowerCase().includes(filterLower) ||
      c.title.toLowerCase().includes(filterLower)
    );
    if (matched.length > 0) {
      pool = matched;
    }
  }

  // Filter out any IDs already displayed if possible
  const filtered = pool.filter((c) => !excludeIds.includes(c.id));
  const source = filtered.length >= count ? filtered : pool;

  // Modern Fisher-Yates Shuffle
  const shuffled = [...source];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}
